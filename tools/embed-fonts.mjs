// Regenerates src/fonts.js from assets/fonts/*.woff2 so the player works offline,
// including when opened directly from disk (file://), where Chrome blocks font URLs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const weights = { 600: 'Inter-SemiBold', 700: 'Inter-Bold', 800: 'Inter-ExtraBold' };
const out = Object.entries(weights).map(([w, name]) => {
  const b64 = readFileSync(join(root, 'assets/fonts', `${name}.woff2`)).toString('base64');
  return `  { family: 'SeriesSans', weight: '${w}', src: 'data:font/woff2;base64,${b64}' }`;
});
writeFileSync(
  join(root, 'src/fonts.js'),
  `// Generated by tools/embed-fonts.mjs - Inter (SIL Open Font License), Latin subset.\n` +
    `window.SERIES_FONTS = [\n${out.join(',\n')}\n];\n`
);
console.log('src/fonts.js written');
